/**
 * npm run export:defs
 *
 * Writes tools/art/data/archetypes.json: the structure archetypes and prop kinds the art tools
 * need to build one model per archetype at the right size (ASSETS.md section 3). The source of
 * truth is shared/src/city/archetypes.ts and props.ts; never edit the JSON by hand.
 *
 * Pass `--check` to verify the file on disk is up to date without writing (exit code 1 if not).
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARCHETYPES, archetypeModelId, archetypeSizeClass, PROP_KIND_IDS, PROP_KINDS } from '../src/index';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outFile = resolve(repoRoot, 'tools', 'art', 'data', 'archetypes.json');

const data = {
  note: 'Generated by `npm run export:defs` from shared/src/city/archetypes.ts and props.ts. Do not edit.',
  units: 'meters; footprint is [width along local X, depth along local Z]; the front faces +Z',
  archetypes: ARCHETYPES.map((a) => ({
    id: a.id,
    model: archetypeModelId(a),
    class: a.cls,
    footprint: [a.footprint[0], a.footprint[1]],
    height: a.height,
    sizeClass: archetypeSizeClass(a),
    landmark: a.landmark,
    zones: [...a.zones],
    passable: a.passable,
    hp: a.hp,
    value: a.value,
  })),
  props: PROP_KIND_IDS.map((id) => ({
    id,
    model: `prop_${id}`,
    radius: PROP_KINDS[id].radius,
    height: PROP_KINDS[id].height,
  })),
};

const text = `${JSON.stringify(data, null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {
    current = '';
  }
  if (current !== text) {
    console.error(`${outFile} is out of date. Run: npm run export:defs`);
    process.exit(1);
  }
  console.log(`${outFile} is up to date (${data.archetypes.length} archetypes, ${data.props.length} prop kinds).`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  console.log(`Wrote ${outFile} (${data.archetypes.length} archetypes, ${data.props.length} prop kinds).`);
}
