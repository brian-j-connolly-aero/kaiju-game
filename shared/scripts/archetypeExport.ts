/**
 * Builds the text of tools/art/data/archetypes.json from the code. Shared by the export script
 * and by the test that checks the file on disk is up to date.
 */

import { ARCHETYPES, archetypeModelId, archetypeSizeClass, PROP_KIND_IDS, PROP_KINDS } from '../src/index';

/** Path of the exported file, relative to the repository root. */
export const ARCHETYPE_EXPORT_PATH = 'tools/art/data/archetypes.json';

export function archetypeExportText(): string {
  const data = {
    note: 'Generated by `npm run export:defs` from shared/src/city/archetypes.ts and props.ts. Do not edit.',
    units: 'meters; footprint is [width along local X, depth along local Z]; the front faces +Z',
    archetypes: ARCHETYPES.map((a) => ({
      id: a.id,
      model: archetypeModelId(a),
      class: a.cls,
      footprint: [a.footprint[0], a.footprint[1]],
      height: a.height,
      sizeClass: archetypeSizeClass(a),
      landmark: a.landmark,
      zones: [...a.zones],
      passable: a.passable,
      hp: a.hp,
      value: a.value,
    })),
    props: PROP_KIND_IDS.map((id) => ({
      id,
      model: `prop_${id}`,
      radius: PROP_KINDS[id].radius,
      height: PROP_KINDS[id].height,
    })),
  };
  return `${JSON.stringify(data, null, 2)}\n`;
}
