/** Table index of the heading closest to the ground direction (dx, dz); 0 for the zero vector. */
export function nearestDir(dx: number, dz: number): number {
  let best = 0;
  let bestDot = -Infinity;
  for (let k = 0; k < DIR_COUNT; k++) {
    const d = dx * DIR_SIN[k] + dz * DIR_COS[k];
    if (d > bestDot) {
      bestDot = d;
      best = k;
    }
  }
  return best;
}

/** The index a given number of table steps further round (negative steps turn the other way). */
export function turnDir(dir: number, steps: number): number {
  return (((dir + steps) % DIR_COUNT) + DIR_COUNT) % DIR_COUNT;
}
