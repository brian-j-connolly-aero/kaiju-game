"""Writes docs/audio/VOICE.md from the cast, the chain settings and the measurements, so the
tables in the document are always the ones the build produced."""

from __future__ import annotations

import json

from . import DOC, DOC_DIR, OUT_DIR
from .chains import DEFAULTS, chain_config
from .pipeline import CEILING_DBTP, MP3_QUALITY, OGG_QUALITY, TARGET_LUFS
from .scriptdoc import BRIEFING_BUDGET, WINDOW_SECONDS

FIRST_SCRIPT_LINES = 181        # size of the script before the audio review (section 10)

ENGINE_NAMES = {"rhvoice": "RHVoice", "flite": "Flite", "pico": "Pico (pico2wave)",
                "festival": "Festival", "espeak": "eSpeak NG"}
ORDER = ["Overlord", "Granite", "Beacon", "Tempest", "Anchor", "Chair"]

WHO = {
    "Overlord": ("Humans", "Command. Stern and unhurried."),
    "Granite": ("Humans", "Squad callsign. The veteran; says as little as possible."),
    "Beacon": ("Humans", "Squad callsign. By the book; reports everything."),
    "Tempest": ("Humans", "Squad callsign. Has taken the creature personally."),
    "Anchor": ("Kaiju", "The Channel 9 news anchor. Total professional calm."),
    "Chair": ("Everyone", "Chair of the committee hearing on the end screen."),
}


def _voice_text(v: dict) -> str:
    parts = [f"{ENGINE_NAMES.get(v['engine'], v['engine'])} `{v.get('voice', '')}`"]
    if v.get("rate", 1.0) != 1.0:
        parts.append(f"rate {v['rate']:g}")
    if v.get("pitch", 1.0) != 1.0:
        parts.append(f"pitch {v['pitch']:g}")
    if v.get("shift_st"):
        parts.append(f"pitch and formants {v['shift_st']:+g} semitones")
    if v.get("pitch_st"):
        parts.append(f"pitch only {v['pitch_st']:+g} semitones")
    return ", ".join(parts)


def _load(name: str):
    p = DOC_DIR / name
    return json.loads(p.read_text()) if p.exists() else None


def _table(head: list[str], rows: list[list], align: str | None = None) -> str:
    out = ["| " + " | ".join(head) + " |"]
    out.append("| " + " | ".join("---:" if align and align[i] == "r" else "---" for i in range(len(head))) + " |")
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def write(lines: list[dict], cast: dict, pron: dict, state: dict, report: dict) -> None:
    from . import notes
    summ = report["summary"]
    by_id = {m["id"]: m for m in report["lines"]}
    speakers = [s for s in ORDER if s in cast["speakers"]] + [s for s in cast["speakers"] if s not in ORDER]
    count = {s: sum(1 for l in lines if l["speaker"] == s) for s in speakers}
    measured = [m for m in report["lines"] if "ogg" in m and "mp3" in m]
    ogg_bytes = sum(m["ogg"]["bytes"] for m in measured)
    mp3_bytes = sum(m["mp3"]["bytes"] for m in measured)
    f0 = {}
    for s in speakers:
        vals = [state["lines"][l["id"]]["f0_median_hz"] for l in lines
                if l["speaker"] == s and l["id"] in state["lines"] and state["lines"][l["id"]].get("f0_median_hz")]
        f0[s] = sorted(vals)[len(vals) // 2] if vals else 0

    doc: list[str] = []
    add = doc.append
    add("# Monster Battle 9001: Voice Lines\n")
    add("<!-- Generated by tools/audio/voice/build.sh (mbvoice/docgen.py and mbvoice/notes.py). "
        "Edit those, not this file. -->\n")
    add(notes.INTRO.format(lines=len(lines), speakers=len(speakers),
                           total_s=summ["all"]["seconds_total"] if "all" in summ else 0,
                           ogg_mb=ogg_bytes / 1e6, mp3_mb=mp3_bytes / 1e6,
                           failures=len(report["failures"])))

    # ---------------------------------------------------------------- cast
    add("## 1. The cast\n")
    rows = []
    for s in speakers:
        sp = cast["speakers"][s]
        g = summ.get("speaker:" + s, {})
        rows.append([f"**{s}**", WHO.get(s, ("", ""))[0], WHO.get(s, ("", ""))[1], _voice_text(sp["voice"]),
                     sp["chain"], f"{f0[s]:.0f}", g.get("words_per_second", ""), count[s]])
    add(_table(["Character", "Heard by", "Who they are", "Synthesizer voice", "Chain", "Pitch (Hz)",
                "Pace (words/s)", "Lines"], rows, "lllllrrr"))
    add("")
    add(notes.CAST_NOTES)

    aud = _load("audition.json")
    if aud:
        add("### Audition: every installed voice on the whole script, unprocessed\n")
        add(notes.AUDITION_INTRO)
        rows = [[r["name"], f"{100 * r['wer']:.1f}", f"{r['f0_median_hz']:.0f}", r["words_per_second"],
                 r["sample_rate"], notes.AUDITION_REMARKS.get(r["name"], "")] for r in aud["main"]]
        add(_table(["Voice", "Word error rate (%)", "Pitch (Hz)", "Pace (words/s)", "Sample rate (Hz)", "Verdict"],
                   rows, "lrrrrl"))
        add("")
        if aud.get("espeak_variants"):
            ev = aud["espeak_variants"]
            best = ", ".join(f"`{r['voice']['voice'].split('+')[1]}` {100 * r['wer']:.0f}%" for r in ev[:8])
            worst = ", ".join(f"`{r['voice']['voice'].split('+')[1]}` {100 * r['wer']:.0f}%" for r in ev[-4:])
            add(notes.ESPEAK_VARIANTS.format(n=len(ev), lines=ev[0]["lines"], best=best, worst=worst,
                                             median=100 * ev[len(ev) // 2]["wer"]))
    exps = _load("experiments.json")
    if exps:
        add("### Casting experiments: candidate settings through the character's own chain\n")
        add(notes.EXPERIMENTS_INTRO)
        titles = {"radio_voices": "Radio candidates (all 93 military lines, first-pass radio chain)",
                  "anchor_voices": "Anchor candidates (all 82 news lines, broadcast chain)",
                  "chair_voices": "Chair candidates, first round (6 hearing lines plus 28 news lines, first-pass hall)",
                  "chair_voices2": "Chair candidates, second round (the 6 hearing lines, final hall chain)"}
        for g, title in titles.items():
            rs = [r for r in exps if r["group"] == g]
            if not rs:
                continue
            add(f"**{title}**\n")
            rows = [[r["label"], r["wer_raw"], r["wer_processed"], f"{r['f0_median_hz']:.0f}", r["words_per_second"]]
                    for r in rs]
            add(_table(["Candidate", "Unprocessed (%)", "Through the chain (%)", "Pitch (Hz)", "Pace (words/s)"],
                       rows, "lrrrr"))
            add("")

    # ---------------------------------------------------------------- chains
    add("## 2. The processing chains\n")
    add(notes.CHAINS_INTRO.format(target=TARGET_LUFS, ceiling=CEILING_DBTP))
    for chain in ("radio", "broadcast", "hall"):
        users = [s for s in speakers if cast["speakers"][s]["chain"] == chain]
        add(f"### {chain.capitalize()} ({', '.join(users)})\n")
        add(notes.CHAIN_TEXT[chain])
        heads = ["Setting", "Default"] + [s for s in users if cast["speakers"][s].get("chain_settings")]
        rows = []
        for k, v in DEFAULTS[chain].items():
            row = [f"`{k}`", json.dumps(v)]
            for s in heads[2:]:
                o = cast["speakers"][s].get("chain_settings", {})
                row.append(json.dumps(o[k]) if k in o else "")
            rows.append(row)
        add(_table(heads, rows))
        add("")
    if exps:
        sweep_titles = [
            ("sweep_radio", "Radio, first pass: one change at a time from 7 dB of drive and an unducked bed at -30 dB "
                            "(31 military lines, Granite's and Beacon's voices)"),
            ("sweep_radio2", "Radio, second pass: one change at a time from 3 dB of drive and a bed at -30 dB that "
                             "drops 10 dB under the words (same 31 lines; Granite's, Beacon's and Tempest's voices)"),
            ("sweep_radio3", "Radio, Tempest's voice only: looking for what costs it words (same 31 lines)"),
            ("sweep_hall", "Hall, first pass: reverberation level and ducking (6 hearing lines plus 28 news lines, "
                           "RHVoice `alan` slowed and lowered)"),
            ("sweep_hall2", "Hall with the voice first tried for the chair (Pico lowered with its own pitch control)"),
        ]
        if any(r["group"].startswith("sweep_") for r in exps):
            add("### Chain sweeps: which settings keep the words\n")
            add(notes.SWEEPS_INTRO)
            for g, title in sweep_titles:
                rs = [r for r in exps if r["group"] == g]
                if not rs:
                    continue
                add(f"**{title}**\n")
                add(_table(["Setting", "Unprocessed (%)", "Through the chain (%)"],
                           [[r["label"], r["wer_raw"], r["wer_processed"]] for r in rs], "lrr"))
                add("")
            add(notes.SWEEPS_AFTER)
    add("Pauses and timing per character:\n")
    rows = []
    for s in speakers:
        sp = cast["speakers"][s]
        ms = [by_id[l["id"]] for l in lines if l["speaker"] == s and "lead_s" in by_id[l["id"]]]
        lead = sum(m["lead_s"] for m in ms) / max(len(ms), 1)
        tail = sum(m["tail_s"] for m in ms) / max(len(ms), 1)
        rows.append([s, sp.get("max_pause_ms", 320), sp.get("min_pause_ms", 0) or "", f"{lead:.2f}", f"{tail:.2f}"])
    add(_table(["Character", "Longest pause allowed (ms)", "Sentence pause at least (ms)",
                "Before the first word (s)", "After the last word (s)"], rows, "lrrrr"))
    add("")

    # ---------------------------------------------------------------- client
    add("## 3. For the client\n")
    radio_ms = [by_id[l["id"]] for l in lines if by_id[l["id"]].get("chain") == "radio" and "lead_s" in by_id[l["id"]]]
    dur = {i: rec["duration"] for i, rec in state["lines"].items()}
    brief = {side: sum(dur.get(l["id"], 0) for l in lines if l["cue"] == "match.briefing" and l["audience"] == side)
             for side in ("humans", "kaiju")}
    orders = [dur[l["id"]] for l in lines if l["cue"] in WINDOW_SECONDS and l["audience"] == "humans"
              and l["id"] in dur] or [0.0]
    add(notes.CLIENT.format(lead=sum(m["lead_s"] for m in radio_ms) / max(len(radio_ms), 1),
                            tail=sum(m["tail_s"] for m in radio_ms) / max(len(radio_ms), 1),
                            brief_h=brief["humans"], brief_k=brief["kaiju"], brief_max=BRIEFING_BUDGET,
                            win_min=min(orders), win_max=max(orders)))

    # ---------------------------------------------------------------- intelligibility
    add("## 4. Intelligibility check\n")
    add(notes.ASR_INTRO)
    rows = []
    for key, name in [("speaker:" + s, f"{s} ({cast['speakers'][s]['chain']})") for s in speakers] + \
                     [("chain:radio", "**All radio lines**"), ("chain:broadcast", "**All broadcast lines**"),
                      ("chain:hall", "**All hall lines**"), ("all", "**Everything**")]:
        g = summ.get(key)
        if g:
            rows.append([name, g["lines"], g["words"], g["wer_raw"], g["wer_processed"], g["wer_ogg"], g["wer_mp3"]])
    add(_table(["Voice or chain", "Lines", "Words", "Unprocessed (%)", "Finished master (%)",
                "Decoded .ogg (%)", "Decoded .mp3 (%)"], rows, "lrrrrrr"))
    add("")
    add(notes.ASR_READING)

    # ---------------------------------------------------------------- weakest
    add("### Weakest lines\n")
    add(notes.WEAK_INTRO)
    scored = []
    for l in lines:
        m = by_id[l["id"]]
        rec = state["lines"].get(l["id"])
        if rec is None or "ogg" not in m:
            continue
        rate = m["ogg"]["errors"] / max(rec["words"], 1)
        scored.append((rate, m["ogg"]["errors"], l, m, rec))
    scored.sort(key=lambda t: (-t[0], -t[1], t[2]["id"]))
    rows = []
    for rate, errs, l, m, rec in [t for t in scored if t[1] >= 2][:25]:
        rows.append([f"`{l['id']}`", l["speaker"], l["text"], m["ogg"]["hyp"] or "(nothing)",
                     f"{errs}/{rec['words']}", f"{rec['raw']['errors']}/{rec['words']}"])
    add(_table(["Line", "Voice", "Subtitle", "What the recognizer heard (.ogg)", "Errors", "Unprocessed"], rows))
    add("")
    clean = sum(1 for t in scored if t[1] == 0)
    one = sum(1 for t in scored if t[1] == 1)
    add(f"Of {len(scored)} lines, {clean} come back word for word from the decoded .ogg, {one} with a single "
        f"wrong word, and {len(scored) - clean - one} with two or more.\n")
    add(notes.WEAK_AFTER)

    # ---------------------------------------------------------------- respellings
    add("## 5. Pronunciation respellings\n")
    add(notes.PRONOUNCE_INTRO)
    rows = []
    for w, rule in pron.get("words", {}).items():
        if isinstance(rule, dict):
            for k, v in rule.items():
                rows.append([f"word `{w}`", k, f"`{v}`", pron.get("why", {}).get(w, "")])
        else:
            rows.append([f"word `{w}`", "every voice", f"`{rule}`", pron.get("why", {}).get(w, "")])
    for i, rule in pron.get("lines", {}).items():
        rows.append([f"line `{i}`", "its speaker", f"`{rule if isinstance(rule, str) else json.dumps(rule)}`",
                     pron.get("why", {}).get(i, "")])
    if rows:
        add(_table(["What", "Applies to", "Fed to the synthesizer", "Why"], rows))
    else:
        add(notes.PRONOUNCE_NONE)
    tried = pron.get("tried", [])
    if tried:
        add(notes.PRONOUNCE_TRIED)
        add(_table(["Line", "Voice", "Respellings tried", "Result"],
                   [[f"`{t['line']}`", t["voice"], "; ".join(f"`{x}`" for x in t["fed"]), t["result"]] for t in tried]))
        add("")

    # ---------------------------------------------------------------- measurements
    add("## 6. Measurements of the finished files\n")
    add(notes.MEASURE_INTRO.format(target=TARGET_LUFS, ogg_q=OGG_QUALITY, mp3_q=MP3_QUALITY))
    rows = []
    for s in speakers + ["all"]:
        g = summ.get("speaker:" + s if s != "all" else "all")
        if not g:
            continue
        rows.append([s if s != "all" else "**Everything**", g["lines"], g["seconds_min"], g["seconds_mean"],
                     g["seconds_max"], g["seconds_total"], f"{g['lufs_min']:.1f} to {g['lufs_max']:.1f}",
                     f"{g['peak_max']:.1f}"])
    add(_table(["Voice", "Lines", "Shortest (s)", "Mean (s)", "Longest (s)", "Total (s)",
                "Loudness (LUFS)", "Highest true peak (dBTP)"], rows, "lrrrrrrr"))
    add("")
    longest = sorted(measured, key=lambda m: -state["lines"][m["id"]]["duration"])[:5]
    add("Longest lines: " + ", ".join(f"`{m['id']}` {state['lines'][m['id']]['duration']:.1f} s" for m in longest) + ".\n")
    slow = sorted(measured, key=lambda m: -m["seconds_per_word"])[:5]
    add("Slowest delivery (seconds per word, speech only): "
        + ", ".join(f"`{m['id']}` {m['seconds_per_word']:.2f}" for m in slow) + ".\n")
    radio = [m for m in measured if m["chain"] == "radio"]
    if radio:
        add(f"Radio band: across the {len(radio)} radio lines at most "
            f"{100 * max(m['ogg']['share_below_band'] for m in radio):.2f}% of the energy lies below two thirds of "
            f"the lower band corner (200 Hz for the squads) and at most "
            f"{100 * max(m['ogg']['share_above_band'] for m in radio):.2f}% above 1.3 times the upper corner "
            f"(4.9 kHz for the squads); on average "
            f"{100 * sum(m['ogg']['share_in_band'] for m in radio) / len(radio):.1f}% lies inside the band.\n")
    sq = [m["squelch"] for m in radio if "squelch" in m]
    if sq:
        med = lambda k: sorted(q[k] for q in sq)[len(sq) // 2]
        add(f"Squelch and static, measured on the decoded `.ogg` of every radio line against the speech they frame: "
            f"the key click at the start peaks {-med('open_click_db'):.0f} dB below the loudest speech peak "
            f"(never less than {-max(q['open_click_db'] for q in sq):.0f} dB below), the one at the end "
            f"{-med('close_click_db'):.0f} dB below (never less than {-max(q['close_click_db'] for q in sq):.0f} dB); "
            f"the bursts of static are {-med('open_burst_db'):.0f} dB and {-med('close_burst_db'):.0f} dB below the "
            f"loud parts of the speech; the static bed before the first word is {-med('static_db'):.0f} dB below "
            f"them.\n")
    if report["failures"]:
        add("**Checks that failed in the last build:**\n")
        for f in report["failures"]:
            add(f"- {f}")
        add("")
    else:
        add(notes.CHECKS_PASSED.format(window=max(WINDOW_SECONDS.values()), brief_max=BRIEFING_BUDGET))
    enc = _load("encoding.json")
    if enc and enc.get("settings"):
        from .analyze import PEAK_LIMIT_DBTP
        rows = [[("**" if r["shipped"] else "") + ("Vorbis " if r["format"] == "ogg" else "MP3 ") + r["quality"]
                 + (" (used)**" if r["shipped"] else ""), r["megabytes"], r["kbit_per_s"], r["wer_all"],
                 r["wer_radio"], r["snr_median_db"], f"{r['true_peak_max_db']:.2f}"] for r in enc["settings"]]
        add(notes.ENCODING.format(ogg_q=OGG_QUALITY, mp3_q=MP3_QUALITY, lines=enc["settings"][0]["lines"],
                                  ceiling=CEILING_DBTP, peak_limit=PEAK_LIMIT_DBTP))
        add(_table(["Setting", "All files (MB)", "Bit rate (kbit/s)", "Word errors, all lines (%)",
                    "Word errors, radio lines (%)", "Signal to noise, median (dB)", "Highest true peak (dBTP)"],
                   rows, "lrrrrrr"))
        add("")
        add(notes.ENCODING_AFTER.format(kb_per_line=ogg_bytes / 1000 / max(len(measured), 1)))
    sheets = sorted(p.name for p in DOC_DIR.glob("sheet_*.png"))
    if sheets:
        add("Spectrogram sheets (three lines per voice; synthesizer output on the left, finished clip on the right): "
            + ", ".join(f"[{n}](voice/{n})" for n in sheets) + ".\n")

    add("## 7. What is weak, and what to do about it\n")
    wer = lambda s: summ.get("speaker:" + s, {}).get("wer_ogg", 0)
    add(notes.WEAK_POINTS.format(tempest_wer=wer("Tempest")))
    add("## 8. Swapping the synthesizer\n")
    add(notes.SWAP)
    add("## 9. Rebuilding\n")
    add(notes.REBUILD.format(out=OUT_DIR.relative_to(OUT_DIR.parents[4])))
    add("## 10. What the audio review changed\n")
    add(notes.REVIEW.format(win_min=min(orders), win_max=max(orders), window=max(WINDOW_SECONDS.values()),
                            new_lines=len(lines) - FIRST_SCRIPT_LINES, lines=len(lines),
                            tempest_wer=wer("Tempest"), granite_wer=wer("Granite"),
                            brief_h=brief["humans"], brief_max=BRIEFING_BUDGET))
    DOC.write_text("\n".join(doc).rstrip() + "\n")
