"""Writes docs/audio/VOICE.md from the cast, the chain settings and the measurements, so the
tables in the document are always the ones the build produced."""

from __future__ import annotations

from . import DOC
from .chains import DEFAULTS
from .pipeline import CEILING_DBTP, MP3_QUALITY, OGG_QUALITY, TARGET_LUFS

ENGINE_NAMES = {"kokoro": "Kokoro-82M", "piper": "Piper", "rhvoice": "RHVoice", "flite": "Flite",
                "pico": "Pico (pico2wave)", "festival": "Festival", "espeak": "eSpeak NG"}
ORDER = ["Granite", "Beacon", "Tempest", "Anvil", "Anchor"]
WHO = {
    "Granite": ("Everyone (radio)", "Squad 1's leader, shouting into the radio."),
    "Beacon": ("Everyone (radio)", "Squad 2's leader."),
    "Tempest": ("Everyone (radio)", "Squad 3's leader."),
    "Anvil": ("Everyone (radio)", "Squad 4's leader."),
    "Anchor": ("The monster's player", "The Channel 9 news anchor: total professional calm."),
}


def _voice_text(v: dict) -> str:
    parts = [f"{ENGINE_NAMES.get(v['engine'], v['engine'])} `{v.get('voice', '')}`"]
    if v.get("rate", 1.0) != 1.0:
        parts.append(f"rate {v['rate']:g}")
    if v.get("pitch_st"):
        parts.append(f"pitch {v['pitch_st']:+g} semitones")
    if v.get("shift_st"):
        parts.append(f"pitch and formants {v['shift_st']:+g} semitones")
    if v.get("shout"):
        parts.append(f"{v['shout']} exclamation marks")
    return ", ".join(parts)


def _table(head: list[str], rows: list[list], align: str) -> str:
    out = ["| " + " | ".join(head) + " |",
           "| " + " | ".join("---:" if a == "r" else "---" for a in align) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def write(lines: list[dict], cast: dict, pron: dict, state: dict, report: dict) -> None:
    summ = report["summary"]
    speakers = [s for s in ORDER if s in cast["speakers"]] + [s for s in cast["speakers"] if s not in ORDER]
    count = {s: sum(1 for l in lines if l["speaker"] == s) for s in speakers}
    measured = [m for m in report["lines"] if "ogg" in m and "mp3" in m]
    ogg_mb = sum(m["ogg"]["bytes"] for m in measured) / 1e6
    mp3_mb = sum(m["mp3"]["bytes"] for m in measured) / 1e6
    total_s = summ.get("all", {}).get("seconds_total", 0)

    d: list[str] = []
    add = d.append
    add("# Monster Battle 9001: Voice Lines\n")
    add("<!-- Generated by tools/audio/voice/build.sh (mbvoice/docgen.py). Edit that, not this file. -->\n")
    add(f"Every spoken line in the game as a finished sound file: **{len(lines)} lines, {len(speakers)} voices, "
        f"{total_s:.0f} seconds of audio**, each as `.ogg` (Vorbis, quality {OGG_QUALITY}) and `.mp3` (quality "
        f"{MP3_QUALITY}), {ogg_mb:.1f} MB and {mp3_mb:.1f} MB in all. The words are in `docs/VOICE_SCRIPT.md`; this "
        "page is about how they are spoken, processed and checked.\n")
    add("Since round 4 (`docs/ROADMAP.md`) almost every line is one a player chooses: the communication rose's "
        "army lines, shouted by the squad leaders over the radio (each squad in its own voice). The only line the "
        "game says by itself is the news telling the monster's player that the creature can molt.\n")
    add("- Sound files: `client/public/assets/audio/voice/<lineId>.ogg` and `.mp3`")
    add("- Manifest: `client/public/assets/manifest.voice.json` (section `voice`, with each line's length)")
    add("- Generator: `tools/audio/voice/` (`build.sh` rebuilds only what changed; `--force` rebuilds everything)")
    add("- Measurements behind this page: `docs/audio/voice/measurements.json`; one picture per voice, "
        "`docs/audio/voice/sheet_<voice>.png` (unprocessed speech left, finished clip right)\n")
    add("The voices are neural speech models (Kokoro-82M, and Piper for one voice) run on the build machine's "
        "processor with no network; the model files are downloaded once into a folder outside the repository. "
        "Nobody listened while these were made (the build machine has no speakers): the build checks every file "
        "by measurement, and two speech recognizers transcribe every finished clip.\n")
    add(f"The last build finished with **{len(report['failures'])} failed checks**.\n")

    add("## 1. The cast\n")
    rows = []
    for s in speakers:
        sp = cast["speakers"][s]
        g = summ.get("speaker:" + s, {})
        rows.append([f"**{s}**", WHO.get(s, ("", ""))[0], WHO.get(s, ("", ""))[1], _voice_text(sp["voice"]), sp["chain"],
                     g.get("words_per_second", ""), count[s]])
    add(_table(["Voice", "Heard by", "Who", "Speech model", "Chain", "Pace (words/s)", "Lines"], rows, "lllllrr"))
    add("")
    add("**Shouting.** The squad leaders are pushed to yell: faster speech, the pitch raised a semitone or two, "
        "extra exclamation marks fed to the speech model (the subtitle keeps one), and a hotter radio chain than the "
        "default: more compression, more overdrive into the clipper, a narrower band and louder static. Their "
        "chain settings, against the radio defaults:\n")
    radio = DEFAULTS["radio"]
    rows = []
    for s in speakers:
        sp = cast["speakers"][s]
        if sp["chain"] != "radio":
            continue
        over = sp.get("chain_settings") or {}
        rows.append([f"**{s}**"] + [str(over.get(k, radio[k])) for k in ("band_hz", "drive_db", "comp_threshold_db", "comp_ratio", "presence_db", "static_db")])
    rows.append(["*default*"] + [str(radio[k]) for k in ("band_hz", "drive_db", "comp_threshold_db", "comp_ratio", "presence_db", "static_db")])
    add(_table(["Voice", "Band (Hz)", "Overdrive (dB)", "Compressor threshold (dB)", "Ratio", "Presence (dB)", "Static (dB)"],
               rows, "lrrrrrr"))
    add("")

    add("## 2. The checks\n")
    add(f"Every file is decoded again and measured: loudness {TARGET_LUFS:g} LUFS (loudness units relative to full "
        f"scale) within 0.8, true peak under -0.5 dB (decibels) of full scale (mastered to {CEILING_DBTP:g}), clean "
        "edges, radio lines band-limited, a rose line at most 4.5 seconds, and what the two speech recognizers hear: "
        "pocketsphinx (old, strict, easily thrown by radio grit) and a modern recognizer. Word errors are the words "
        "a recognizer got wrong, per hundred words of the line.\n")
    rows = []
    for key, name in [("speaker:" + s, s) for s in speakers] + [("all", "**Everything**")]:
        g = summ.get(key)
        if not g:
            continue
        rows.append([name, g["lines"], f"{g['seconds_min']:.1f} to {g['seconds_max']:.1f}", f"{g['lufs_min']:.1f} to {g['lufs_max']:.1f}",
                     f"{g['peak_max']:.1f}", f"{g['wer2_ogg']:.1f}", f"{g['wer_ogg']:.1f}"])
    add(_table(["Voice", "Lines", "Seconds", "Loudness (LUFS)", "Highest peak (dB)", "Word errors, modern",
                "Word errors, pocketsphinx"], rows, "lrrrrrr"))
    add("")
    misheard = sorted((m for m in measured if m["ogg"].get("errors2", 0) > 0), key=lambda m: -m["ogg"]["errors2"])
    if misheard:
        add("Lines the modern recognizer did not hear word for word (listen to these first):\n")
        by_id = {l["id"]: l for l in lines}
        for m in misheard[:12]:
            add(f"- `{m['id']}` \"{by_id[m['id']]['text']}\": heard \"{m['ogg'].get('hyp2', '')}\"")
        add("")
    else:
        add("The modern recognizer heard every finished line word for word.\n")
    if report["failures"]:
        add("Failed checks:\n")
        for f in report["failures"]:
            add(f"- {f}")
        add("")

    add("## 3. Changing the lines\n")
    add("- Words: `client/src/audio/roseLines.json` (the rose) or `shared/src/defs/voiceLines.json` (the molt line); "
        "then `tools/audio/voice/build.sh` and `npm run assets:manifest`. The rules are in `docs/VOICE_SCRIPT.md`.")
    add("- A voice: `tools/audio/voice/cast.json`. A different speech service: replace `synthesize` in "
        "`tools/audio/voice/mbvoice/synth.py`; everything after it (radio chain, loudness, files, checks) stays.")
    add("- Respellings fed to the speech model (the subtitle never changes): `tools/audio/voice/pronounce.json`.")
    DOC.write_text("\n".join(d) + "\n")
