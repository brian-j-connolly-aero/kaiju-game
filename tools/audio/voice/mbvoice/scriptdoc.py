"""Writes docs/VOICE_SCRIPT.md: the readable copy of the voice script, for people who write or
reword lines. The words themselves live in shared/src/defs/voiceLines.json (the monster's molt
line) and client/src/audio/roseLines.json (the communication rose's army lines)."""

from __future__ import annotations

from collections import defaultdict

from . import REPO
from .scriptcheck import MAX_WORDS, ROSE_MAX, ROSE_MIN, SQUAD_VOICES

DOC = REPO / "docs" / "VOICE_SCRIPT.md"

WEDGES = {
    "panic": "Panic",
    "bravado": "Bravado",
    "orders": "Orders",
    "science": "Science (somebody call the professor)",
    "home": "Home (my mother lives on this street)",
    "food": "Food",
    "retreat": "Retreat",
    "admire": "Admiring the monster",
}


def write(lines: list[dict], state: dict, report: dict | None = None) -> None:
    measured = {m["id"]: m for m in (report or {}).get("lines", [])}
    cue_lines = [l for l in lines if not l["cue"].startswith("rose.")]
    rose: dict[str, list[dict]] = defaultdict(list)
    for l in lines:
        if l["cue"].startswith("rose.") and l["speaker"] == SQUAD_VOICES[0]:
            rose[l["cue"][5:]].append(l)
    rose_count = sum(1 for l in lines if l["cue"].startswith("rose."))

    out: list[str] = []
    w = out.append
    w("# Monster Battle 9001: Voice Script\n")
    w("<!-- Generated by tools/audio/voice/build.sh (mbvoice/scriptdoc.py). Edit the script files, "
      "not this page. -->\n")
    w("Every spoken line in the game. Since round 4 (`docs/ROADMAP.md`) the game says nothing by "
      "itself except one thing: the news tells the monster's player that the creature can molt. "
      "Everything else is talk the players choose with the **communication rose** (hold the rose "
      "key, pick a wedge, let go): the army shouts schlocky 1950s monster-movie radio nonsense, the "
      "monster roars, snuffles and sings (its noises are sound effects, not lines: "
      "`docs/audio/SFX.md`). None of it changes the game.\n")
    w(f"- **{len(cue_lines)} news line(s)** for the monster's molt, in "
      "`shared/src/defs/voiceLines.json`.")
    w(f"- **{len(rose)} army wedges** with their lines in `client/src/audio/roseLines.json`. Every "
      f"sentence is spoken in each of the {len(SQUAD_VOICES)} squad voices "
      f"({', '.join(SQUAD_VOICES)}), so the {sum(len(v) for v in rose.values())} sentences make "
      f"{rose_count} sound files, `rose_<voice>_<wedge>_<number>`. A player's squad always speaks "
      "in its own voice; the subtitle shows the player's name and the words.")
    w("- A later pass with a commercial voice service can rebuild every file from the same two "
      "files: change the voices in `tools/audio/voice/cast.json` (or replace `mbvoice/synth.py`) "
      "and run `tools/audio/voice/build.sh --force`.\n")

    w("## The monster's molt (news, heard by the monster's player)\n")
    w("Said by the news anchor when the destruction bar reaches the next molt marker.\n")
    w("| Line | Words | Seconds |")
    w("| --- | --- | ---: |")
    for l in cue_lines:
        rec = state["lines"].get(l["id"], {})
        w(f"| `{l['id']}` | {l['text']} | {rec.get('duration', 0):.1f} |")
    w("")

    w("## The army's rose (radio, heard by everyone)\n")
    w("Every screen plays the same line: the server picks it at random when the wedge is sent. "
      "Lengths are the shortest and longest of the four voices.\n")
    for wedge, ls in rose.items():
        w(f"### {WEDGES.get(wedge, wedge)} (`{wedge}`)\n")
        w("| # | Words | Seconds |")
        w("| ---: | --- | ---: |")
        for n, l in enumerate(ls, start=1):
            durs = [state["lines"].get(f"rose_{v.lower()}_{wedge}_{n}", {}).get("duration") for v in SQUAD_VOICES]
            durs = [d for d in durs if d]
            span = f"{min(durs):.1f} to {max(durs):.1f}" if durs else ""
            w(f"| {n} | {l['text']} | {span} |")
        w("")

    w("## Rules for writing new lines\n")
    w("The build checks all of these and refuses to run when one is broken "
      "(`tools/audio/voice/mbvoice/scriptcheck.py`).\n")
    w(f"- A rose line is **one sentence**, at most {MAX_WORDS} words, shouted: it ends with one "
      "exclamation mark (the voices get more of them when spoken, which the build adds). A wedge "
      f"has {ROSE_MIN} to {ROSE_MAX} lines.")
    w("- The tone: an absurd world played completely straight. Earnest, inane, never mean, nothing "
      "gory, nothing about any real faith.")
    w("- Only letters, spaces, commas, periods and exclamation marks; no apostrophes (say \"it is\", "
      "not \"it's\"); every word in the speech recognizer's dictionary, so the build can check that "
      "it is heard; no word that can be said two ways (\"live\", \"close\", \"wind\", \"upset\"); no "
      "words in capitals (they would be spelled out).")
    w("- Try a wording first: `tools/audio/voice/tryline.py Granite \"Your line here!\"` speaks it in "
      "that voice and chain and prints what the recognizer hears.")
    w("- A new wedge needs a picture and its place at the end of `ROSE_ARMY` in "
      "`shared/src/net/rose.ts`.\n")
    if measured:
        heard = [m for m in measured.values() if "ogg" in m and m["ogg"].get("errors2", 0) == 0]
        w(f"In the last build the modern speech recognizer heard {len(heard)} of {len(measured)} finished "
          "lines word for word (`docs/audio/VOICE.md` has the details).")
    DOC.write_text("\n".join(out) + "\n")
